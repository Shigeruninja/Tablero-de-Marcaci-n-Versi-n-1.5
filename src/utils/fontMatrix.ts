// Obtener la matriz de bits según el tamaño configurado
export function getFontBitmap(char: string, size: MatrixFontSize = '3x5'): { bitmap: number[]; width: number; height: number; step: number } {
  const upper = char.toUpperCase();
  if (size === '3x5') {
    const bitmap = FONT_3X5[upper] || FONT_3X5[' '] || [0, 0, 0, 0, 0];
    return { bitmap, width: 3, height: 5, step: 4 };
  } else if (size === '4x6') {
    const bitmap = FONT_4X6[upper] || FONT_4X6[' '] || [0, 0, 0, 0, 0, 0];
    return { bitmap, width: 4, height: 6, step: 5 };
  } else {
    const bitmap = FONT_5X7_EXTENDED[upper] || FONT_5X7_EXTENDED[' '] || [0, 0, 0, 0, 0, 0, 0];
    return { bitmap, width: 5, height: 7, step: 6 };
  }
}

// Normalizar texto para caracteres acentuados a mayúsculas
export function sanitizeBannerText(text: string): string {
  return text
    .toUpperCase()
    .replace(/[ÀÂÄ]/g, 'A')
    .replace(/[ÈÊË]/g, 'E')
    .replace(/[ÌÎÏ]/g, 'I')
    .replace(/[ÒÔÖ]/g, 'O')
    .replace(/[ÙÛÜ]/g, 'U');
}

// Formatear el periodo/cuarto/set según el deporte activo para la retícula LED (3x5)
export function formatSportPeriodDisplay(sport: string, rawPeriod: string): string {
  const p = (rawPeriod || '1').trim().toUpperCase();

  // Si ya contiene explícitamente el término completo, respetarlo
  if (p.includes('TIEMPO') || p.includes('SET') || p.includes('CUARTO') || p.includes('PERIODO')) {
    return p;
  }

  // Tiempos extras / Overtime / Alargue
  if (p === 'OT' || p === 'TE' || p === 'E' || p === 'EXTRA' || p === 'T.EXTRA' || p === 'ALARGUE' || p === 'PRO') {
    return 'T EXTRA';
  }

  // Básquetbol -> "1 CUARTO", "2 CUARTO", "3 CUARTO", "4 CUARTO"
  if (sport === 'basketball') {
    const num = p.replace(/[^0-9]/g, '') || '1';
    return `${num} CUARTO`;
  }

  // Vóleibol -> "1 SET", "2 SET", "3 SET", "4 SET", "5 SET"
  if (sport === 'volleyball') {
    if (p === 'TB' || p === 'TIEBREAK') {
      return '5 SET';
    }
    const num = p.replace(/[^0-9]/g, '') || '1';
    return `${num} SET`;
  }

  // Fútbol / Futsal / Handball -> "1 TIEMPO", "2 TIEMPO"
  if (sport === 'soccer' || sport === 'futsal' || sport === 'handball') {
    const num = p.replace(/[^0-9]/g, '') || '1';
    return `${num} TIEMPO`;
  }

  // Personalizado / Otros -> "1 PERIODO", "2 PERIODO"
  const num = p.replace(/[^0-9]/g, '') || '1';
  return `${num} PERIODO`;
}

